type MessageKey = keyof typeof messages.en

type I18nContextValue = {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: (key: MessageKey) => string
  tx: (text: string) => string
}

const localeByLanguage: Record<Language, string> = {
  en: "en-US",
  fr: "fr-FR",
}

let currentLanguage: Language = "en"

const I18nContext = createContext<I18nContextValue | null>(null)

function detectInitialLanguage(): Language {
  if (typeof window === "undefined") {
    return "en"
  }
  const stored = window.localStorage.getItem(languageStorageKey)
  if (stored === "en" || stored === "fr") {
    return stored
  }
  return window.navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(detectInitialLanguage)

  useEffect(() => {
    currentLanguage = language
    if (typeof window !== "undefined") {
      window.localStorage.setItem(languageStorageKey, language)
      document.documentElement.lang = localeByLanguage[language]
    }
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: localeByLanguage[language],
    setLanguage: setLanguageState,
    t: (key) => messages[language][key],
    tx: (text) => (phrases[language] as Record<string, string>)[text] ?? text,
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider")
  }
  return context
}

export function getCurrentLocale() {
  return localeByLanguage[currentLanguage]
}

export function translatePhrase(text: string) {
  return (phrases[currentLanguage] as Record<string, string>)[text] ?? text
}
